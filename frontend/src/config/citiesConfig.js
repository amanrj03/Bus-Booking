/**
 * Normalizes text to Title Case (e.g., "patna" -> "Patna")
 */
export function toTitleCase(str = '') {
  return str
    .toLowerCase()
    .split(' ')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
    .trim();
}

/**
 * Combine built-in Indian cities catalog with any dynamic cities from DB/API
 */
export function getUnifiedCities(dynamicCities = []) {
  const map = new Map();

  for (const c of INDIAN_CITIES_CATALOG) {
    map.set(c.name.toLowerCase(), c);
  }

  for (const item of dynamicCities) {
    const cityName = typeof item === 'string' ? item : item?.name || item?.sourceCity || item?.destinationCity;
    if (cityName && typeof cityName === 'string' && cityName.trim()) {
      const lower = cityName.trim().toLowerCase();
      if (!map.has(lower)) {
        map.set(lower, {
          name: toTitleCase(cityName),
          state: 'India',
          hub: 'Central Bus Terminal',
        });
      }
    }
  }

  return Array.from(map.values());
}

/**
 * Smart Filter:
 * - When query is empty, returns curated top popular Indian travel hubs
 * - Prioritizes prefix matches
 * - Supports substring matching across city name, state, and terminal hubs
 * - If user types any custom city that isn't found, automatically presents an instant
 *   autocomplete candidate so ANY city can be selected!
 */
export function filterCities(allCities, query = '') {
  const q = (query || '').trim().toLowerCase();
  if (!q) {
    const popularSet = new Set(TOP_POPULAR_CITY_NAMES.map((n) => n.toLowerCase()));
    const popular = allCities.filter((c) => popularSet.has(c.name.toLowerCase()));
    const others = allCities.filter((c) => !popularSet.has(c.name.toLowerCase()));
    return [...popular, ...others].slice(0, 12);
  }

  const prefixMatches = [];
  const substringMatches = [];

  for (const city of allCities) {
    const nameLower = city.name.toLowerCase();
    const stateLower = (city.state || '').toLowerCase();
    const hubLower = (city.hub || '').toLowerCase();

    if (nameLower.startsWith(q)) {
      prefixMatches.push(city);
    } else if (
      nameLower.includes(q) ||
      stateLower.includes(q) ||
      hubLower.includes(q)
    ) {
      substringMatches.push(city);
    }
  }

  const results = [...prefixMatches, ...substringMatches];

  // If no exact/partial match, generate an instant selectable city option with formatted title
  if (results.length === 0 && q.length >= 2) {
    results.push({
      name: toTitleCase(query),
      state: 'India',
      hub: 'City Terminal Hub',
      isDynamic: true,
    });
  }

  return results.slice(0, 15);
}

/**
 * Checks whether a given city name matches any recognized city in the catalog
 */
export function isValidCatalogCity(allCities, cityName = '') {
  if (!cityName || !cityName.trim()) return false;
  const q = cityName.trim().toLowerCase();
  return allCities.some((c) => c.name.toLowerCase() === q);
}
